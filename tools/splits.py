"""splits.py

Writes the provisional config/splits.txt: a partition of every XBE section's
file-backed bytes into ranges. Code is cut at every function start and every
tail chunk start the IDA database records, so any function or EH funclet can
be replaced by compiled code on its own. Data sections are single ranges
until M5 splits them.

The ranges are placement boundaries, not yet translation units; M1's unit
recovery groups them later.

Line format:  0xSTART  0xEND  SECTION  NAME"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xbe import Xbe  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def read_table(name, columns):
    rows = []
    for line in open(os.path.join(ROOT, 'config', name)):
        if line.startswith('#') or not line.strip():
            continue
        rows.append(line.split(None, columns - 1))
    return rows


def main():
    image = Xbe(os.path.join(ROOT, 'orig', 'Game_XboxMultiplayer.xbe'))
    names = {}
    points = set()
    for row in read_table('symbols.txt', 5):
        address = int(row[0], 16)
        if row[1] == 'function':
            points.add(address)
            names[address] = row[4].strip()
    for row in read_table('chunks.txt', 3):
        address = int(row[0], 16)
        points.add(address)
        names.setdefault(address, 'chunk_of_%s' % row[2].strip().replace('0x', '').lstrip('0'))
    out = open(os.path.join(ROOT, 'config', 'splits.txt'), 'w', newline='\n')
    out.write('# Generated by tools/splits.py. Provisional placement ranges: code is cut at\n')
    out.write('# every IDA function start and tail chunk; data sections are whole.\n')
    out.write('# 0xSTART  0xEND  SECTION  NAME\n')
    total = 0
    for section in image.sections:
        lo, hi = section['va'], section['va'] + section['rsize']
        cuts = sorted(p for p in points if lo < p < hi)
        bounds = [lo] + cuts + [hi]
        for start, end in zip(bounds, bounds[1:]):
            out.write('0x%08X 0x%08X %-10s %s\n' % (start, end, section['name'],
                                                   names.get(start, '-')))
            total += 1
    out.close()
    print('config/splits.txt: %d ranges over %d sections' % (total, len(image.sections)))


if __name__ == '__main__':
    main()
