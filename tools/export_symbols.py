"""export_symbols.py

Writes config/symbols.txt from the live IDA database: one line per function
and per named address, with the name exactly as the database has it. Rule 3 of
the plan: names are copied, never invented; `sub_XXXXXX` stays `sub_XXXXXX`.

Line format:  0xADDRESS  KIND  SIZE  SECTION  NAME
KIND is `function` or `data`; SIZE is 0 where the database records none.

IDA is reached through the port repository's client (an allowed analysis
input); set CODFH_IDA_CLIENT to use another copy."""
import json
import os
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from xbe import Xbe  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLIENT = os.environ.get('CODFH_IDA_CLIENT', r'C:\codfh\tools\ida_client.py')
BINARY = 'Game_XboxMultiplayer.xbe'


def dump():
    raw = os.path.join(ROOT, 'build', 'ida_names.json')
    if not os.path.isdir(os.path.dirname(raw)):
        os.makedirs(os.path.dirname(raw))
    script = os.path.join(ROOT, 'tools', 'ida_dump_names.py')
    args = json.dumps({'file_path': script})
    subprocess.check_call([sys.executable, CLIENT, '--binary', BINARY, '--tool',
                           'py_exec_file', '--args', args, '--output', raw],
                          cwd=os.path.dirname(os.path.dirname(CLIENT)))
    result = json.load(open(raw, encoding='utf-8'))
    stdout = result.get('stdout') if isinstance(result, dict) else None
    if not stdout:
        raise SystemExit('IDA returned no output: %r' % (result,)[:400])
    return json.loads(stdout)


def main():
    data = dump()
    image = Xbe(os.path.join(ROOT, 'orig', BINARY))
    rows = {}
    for ea, name, size in data['functions']:
        rows[ea] = ('function', size, name)
    for ea, name in data['names']:
        if ea not in rows:
            rows[ea] = ('data', 0, name)
    out = os.path.join(ROOT, 'config', 'symbols.txt')
    with open(out, 'w', newline='\n') as f:
        f.write('# Generated by tools/export_symbols.py from the live IDA database.\n')
        f.write('# 0xADDRESS  KIND  SIZE  SECTION  NAME\n')
        for ea in sorted(rows):
            kind, size, name = rows[ea]
            section = image.section_at(ea)
            f.write('0x%08X %-8s 0x%-6X %-10s %s\n' % (
                ea, kind, size, section['name'] if section else '-', name))
    functions = sum(1 for r in rows.values() if r[0] == 'function')
    print('%s: %d functions, %d data names' % (out, functions, len(rows) - functions))
    chunks = os.path.join(ROOT, 'config', 'chunks.txt')
    with open(chunks, 'w', newline='\n') as f:
        f.write('# Generated by tools/export_symbols.py: function tail chunks from the IDA\n')
        f.write('# database (EH funclets and other code placed apart from its function).\n')
        f.write('# 0xSTART  SIZE  OWNER\n')
        for start, size, owner in sorted(data.get('chunks', [])):
            f.write('0x%08X 0x%-6X 0x%08X\n' % (start, size, owner))
    print('%s: %d tail chunks' % (chunks, len(data.get('chunks', []))))


if __name__ == '__main__':
    main()
